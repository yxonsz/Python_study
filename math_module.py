import math

print('파이 상수: ', math.pi)
print('자연상수 e :', math.e)
print('올림 - 3.5의 올림 :', math.ceil(3.5))
print('내림 - 3.5의 내림 :', math.floor(3.5))
print('반올림 - 3.5의 반올림 :', round(3.5))
print('팩토리얼 - 5!(5계승) :', math.factorial(5))
print('최대 공약수 - 28과 70 :', math.gcd(28,70))
print('최소 공배수 - 28과 70 :', math.lcm(28,70))
print('거듭제곱 - 2의 10승 :',  math.pow(2,10))